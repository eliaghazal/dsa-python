million = list(range(1, 1000001))
sum_of_million = sum(million)
print(f"The sum of the first one million numbers is: {sum_of_million}")
min_of_million = min(million)
print(f"The minimum number in the list is: {min_of_million}")
max_of_million = max(million)
print(f"The maximum number in the list is: {max_of_million}")
    
